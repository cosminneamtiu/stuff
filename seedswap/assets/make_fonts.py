#!/usr/bin/env python3
"""Pre-render SeedSwap's UI fonts into 8-bit alpha atlases as C source.

The console build then needs no TrueType rasteriser: gfx.c blends these
glyph bitmaps directly. Font: Ubuntu (variable, Ubuntu Font Licence 1.0,
assets/fonts/UBUNTU-FONT-LICENCE.txt).

    python assets/make_fonts.py            (from tools/seedswap/)
writes source/font_data.c and source/font_data.h.
"""
from pathlib import Path

from PIL import Image, ImageFont

HERE = Path(__file__).resolve().parent
FONT = HERE / "fonts" / "Ubuntu[wdth,wght].ttf"
OUT_C = HERE.parent / "source" / "font_data.c"
OUT_H = HERE.parent / "source" / "font_data.h"

# (enum name, pixel size, weight axis value)
FACES = [
    ("FONT_SMALL", 19, 400),
    ("FONT_BODY", 23, 400),
    ("FONT_BODY_BOLD", 23, 600),
    ("FONT_TITLE", 28, 700),
    ("FONT_HERO", 40, 700),
]
EXTRA = [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2122,
         0x2190, 0x2191, 0x2192, 0x2193, 0x2713, 0x2715, 0x25B6, 0x25CF]
CODEPOINTS = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + EXTRA
ATLAS_W = 512


def has_glyph(font, cp):
    """Pillow draws .notdef for missing glyphs; compare against a private-use point."""
    if cp == 0x20 or cp == 0xA0:
        return True
    def raw(c):
        m = font.getmask(c)
        return (m.size, bytes(m))
    return raw(chr(cp)) != raw(chr(0xE000))


def render_face(size, weight):
    font = ImageFont.truetype(str(FONT), size)
    font.set_variation_by_axes([100, weight])
    ascent, descent = font.getmetrics()
    glyphs, bitmaps = [], []
    for cp in CODEPOINTS:
        if not has_glyph(font, cp):
            continue
        mask, offset = font.getmask2(chr(cp), mode="L")
        w, h = mask.size
        img = Image.frombytes("L", (w, h), bytes(mask)) if w and h else None
        adv = round(font.getlength(chr(cp)))
        # offset is relative to the text origin (top of the ascent box)
        glyphs.append([cp, 0, 0, w, h, offset[0], offset[1], adv])
        bitmaps.append(img)
    # shelf packing
    x = y = shelf = 0
    for g, img in zip(glyphs, bitmaps):
        w, h = g[3], g[4]
        if x + w + 1 > ATLAS_W:
            x, y, shelf = 0, y + shelf + 1, 0
        g[1], g[2] = x, y
        x += w + 1
        shelf = max(shelf, h)
    atlas_h = y + shelf + 1
    atlas = Image.new("L", (ATLAS_W, atlas_h), 0)
    for g, img in zip(glyphs, bitmaps):
        if img is not None:
            atlas.paste(img, (g[1], g[2]))
    return {"size": size, "ascent": ascent, "descent": descent, "line": ascent + descent + max(2, size // 6),
            "glyphs": glyphs, "atlas": atlas.tobytes(), "atlas_h": atlas_h}


def c_bytes(data, per_line=24):
    rows = []
    for i in range(0, len(data), per_line):
        rows.append(",".join(str(b) for b in data[i:i + per_line]))
    return ",\n".join(rows)


def main():
    faces = [(name, render_face(size, weight)) for name, size, weight in FACES]
    h = ["// Generated by assets/make_fonts.py; do not edit.",
         "#pragma once", "#include <stdint.h>", "",
         "typedef struct { uint32_t cp; uint16_t x, y, w, h; int16_t xoff, yoff, adv; } FontGlyph;",
         "typedef struct { int size, ascent, descent, line, count, atlas_w, atlas_h;",
         "                 const FontGlyph *glyphs; const uint8_t *atlas; } FontFace;",
         "", "enum {"] + [f"    {name}," for name, _ in faces] + ["    FONT_COUNT", "};", "",
         "extern const FontFace font_faces[FONT_COUNT];", ""]
    OUT_H.write_text("\n".join(h), encoding="ascii", newline="\n")
    c = ["// Generated by assets/make_fonts.py from Ubuntu[wdth,wght].ttf (Ubuntu Font Licence 1.0); do not edit.",
         '#include "font_data.h"', ""]
    for i, (name, f) in enumerate(faces):
        c.append(f"static const uint8_t atlas_{i}[{len(f['atlas'])}] = {{\n{c_bytes(f['atlas'])}\n}};")
        rows = ",\n".join("{%d,%d,%d,%d,%d,%d,%d,%d}" % tuple(g) for g in f["glyphs"])
        c.append(f"static const FontGlyph glyphs_{i}[{len(f['glyphs'])}] = {{\n{rows}\n}};")
    c.append("const FontFace font_faces[FONT_COUNT] = {")
    for i, (name, f) in enumerate(faces):
        c.append(f"    {{{f['size']}, {f['ascent']}, {f['descent']}, {f['line']}, {len(f['glyphs'])}, {ATLAS_W}, "
                 f"{f['atlas_h']}, glyphs_{i}, atlas_{i}}},  // {name}")
    c.append("};")
    OUT_C.write_text("\n".join(c) + "\n", encoding="ascii", newline="\n")
    for name, f in faces:
        print(f"{name}: {f['size']}px, {len(f['glyphs'])} glyphs, atlas {ATLAS_W}x{f['atlas_h']}")


if __name__ == "__main__":
    main()
